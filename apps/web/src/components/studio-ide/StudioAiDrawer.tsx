/**
 * Detects whether code snippet is a git diff or contains diff hunks
 */
function isDiffBlock(language: string, code: string): boolean {
  if (language.toLowerCase() === 'diff') return true;
  const lines = code.split('\n');
  let hasAdd = false;
  let hasDel = false;
  for (const line of lines) {
    const trimmed = line.trimStart();
    if (trimmed.startsWith('+') && !trimmed.startsWith('+++')) hasAdd = true;
    if (trimmed.startsWith('-') && !trimmed.startsWith('---')) hasDel = true;
    if (hasAdd && hasDel) return true;
  }
  return false;
}

/**
 * Extracts clean resulting code from diff hunks to apply to editor
 */
function extractCleanCodeFromDiff(diffCode: string): string {
  const lines = diffCode.split('\n');
  const clean: string[] = [];
  for (const line of lines) {
    if (
      line.startsWith('---') ||
      line.startsWith('+++') ||
      line.startsWith('@@') ||
      line.startsWith('diff --git')
    ) {
      continue;
    }
    if (line.startsWith('-')) {
      continue; // omit deleted line
    }
    if (line.startsWith('+')) {
      clean.push(line.slice(1)); // strip leading +
    } else {
      clean.push(line);
    }
  }
  return clean.join('\n');
}

/**
 * Line item generated by Myers/LCS diff algorithm
 */
interface DiffLineItem {
  type: 'add' | 'del' | 'eq';
  text: string;
}

/**
 * Computes line-by-line diff between original and modified code
 */
function computeLineDiff(original: string, modified: string): DiffLineItem[] {
  const orig = original.split('\n');
  const mod = modified.split('\n');
  const M = orig.length;
  const N = mod.length;

  if (M > 800 || N > 800) {
    return mod.map((text) => ({ type: 'add' as const, text }));
  }

  const dp: number[][] = Array.from({ length: M + 1 }, () => new Array(N + 1).fill(0));
  for (let i = 0; i < M; i++) {
    for (let j = 0; j < N; j++) {
      if (orig[i] === mod[j]) {
        dp[i + 1][j + 1] = dp[i][j] + 1;
      } else {
        dp[i + 1][j + 1] = Math.max(dp[i + 1][j], dp[i][j + 1]);
      }
    }
  }

  const result: DiffLineItem[] = [];
  let i = M;
  let j = N;

  while (i > 0 || j > 0) {
    if (i > 0 && j > 0 && orig[i - 1] === mod[j - 1]) {
      result.unshift({ type: 'eq', text: orig[i - 1] });
      i--;
      j--;
    } else if (j > 0 && (i === 0 || dp[i][j - 1] >= dp[i - 1][j])) {
      result.unshift({ type: 'add', text: mod[j - 1] });
      j--;
    } else if (i > 0 && (j === 0 || dp[i][j - 1] < dp[i - 1][j])) {
      result.unshift({ type: 'del', text: orig[i - 1] });
      i--;
    }
  }

  return result;
}

/**
 * VS Code styled code block with authentic red deletion pane and lighter green addition pane.
 * Automatically computes diff against active file if AI returns full replacement code.
 */
function CodeBlockCard({
  language,
  code,
  activeFileContent,
  activeSelectionText,
  onApplyCode,
}: {
  language: string;
  code: string;
  activeFileContent?: string | null;
  activeSelectionText?: string | null;
  onApplyCode?: (code: string) => void;
}) {
  const [copied, setCopied] = useState(false);
  const [viewMode, setViewMode] = useState<'diff' | 'clean'>('diff');

  const isExplicitDiff = useMemo(() => isDiffBlock(language, code), [language, code]);
  const cleanCode = useMemo(
    () => (isExplicitDiff ? extractCleanCodeFromDiff(code) : code),
    [isExplicitDiff, code],
  );

  // Auto-diff against active file or selection if not already an explicit diff
  const targetForDiff = activeSelectionText || activeFileContent;
  const autoDiffResult = useMemo(() => {
    if (isExplicitDiff || !targetForDiff || targetForDiff.trim() === cleanCode.trim()) {
      return null;
    }
    const diff = computeLineDiff(targetForDiff, cleanCode);
    const hasModifications = diff.some((l) => l.type !== 'eq');
    if (!hasModifications) return null;

    let add = 0;
    let del = 0;
    for (const l of diff) {
      if (l.type === 'add') add++;
      if (l.type === 'del') del++;
    }
    return { lines: diff, add, del };
  }, [isExplicitDiff, targetForDiff, cleanCode]);

  const hasDiff = isExplicitDiff || autoDiffResult !== null;

  const diffStats = useMemo(() => {
    if (autoDiffResult) {
      return { add: autoDiffResult.add, del: autoDiffResult.del };
    }
    if (!isExplicitDiff) return null;
    const lines = code.split('\n');
    let add = 0;
    let del = 0;
    for (const l of lines) {
      if (l.startsWith('+') && !l.startsWith('+++')) add++;
      if (l.startsWith('-') && !l.startsWith('---')) del++;
    }
    return { add, del };
  }, [autoDiffResult, isExplicitDiff, code]);

  const handleCopy = async () => {
    try {
      const textToCopy = hasDiff && viewMode === 'clean' ? cleanCode : code;
      await navigator.clipboard.writeText(textToCopy);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      // Best effort clipboard
    }
  };

  const handleApply = () => {
    if (!onApplyCode) return;
    onApplyCode(cleanCode);
  };

  const rawLines = useMemo(() => code.split('\n'), [code]);

  return (
    <div className="group my-2 overflow-hidden rounded-xl border border-white/10 bg-black/60 shadow-lg dark:bg-black/80">
      {/* Code Card Toolbar */}
      <div className="flex flex-wrap items-center justify-between border-b border-white/10 bg-white/[0.04] px-3 py-1.5 text-[11px] gap-1.5">
        <div className="flex items-center gap-2">
          <span className="font-mono font-medium text-muted-foreground">
            {language || 'code'}
          </span>
          {diffStats && (
            <div className="flex items-center gap-1 font-mono text-[10px]">
              {diffStats.del > 0 && (
                <span className="rounded bg-rose-950/70 border border-rose-800/40 px-1.5 py-0.2 text-rose-400 font-bold">
                  -{diffStats.del}
                </span>
              )}
              {diffStats.add > 0 && (
                <span className="rounded bg-[#2b593a]/70 border border-[#46c466]/40 px-1.5 py-0.2 text-[#46c466] font-bold">
                  +{diffStats.add}
                </span>
              )}
            </div>
          )}
        </div>

        <div className="flex items-center gap-1.5">
          {hasDiff && (
            <div className="inline-flex rounded-md bg-white/[0.06] p-0.5 text-[10px]">
              <button
                type="button"
                onClick={() => setViewMode('diff')}
                className={cn(
                  'rounded px-1.5 py-0.5 font-medium transition-colors',
                  viewMode === 'diff'
                    ? 'bg-primary/30 text-primary font-bold'
                    : 'text-muted-foreground hover:text-foreground',
                )}
              >
                Diff View
              </button>
              <button
                type="button"
                onClick={() => setViewMode('clean')}
                className={cn(
                  'rounded px-1.5 py-0.5 font-medium transition-colors',
                  viewMode === 'clean'
                    ? 'bg-primary/30 text-primary font-bold'
                    : 'text-muted-foreground hover:text-foreground',
                )}
              >
                Clean
              </button>
            </div>
          )}

          <button
            type="button"
            onClick={handleCopy}
            className="inline-flex items-center gap-1 rounded px-2 py-0.5 text-muted-foreground transition-colors hover:bg-white/10 hover:text-foreground"
            title="Copy code snippet"
          >
            {copied ? (
              <>
                <Check className="h-3 w-3 text-emerald-400" />
                <span className="text-[10px] text-emerald-400">Copied</span>
              </>
            ) : (
              <>
                <Copy className="h-3 w-3" />
                <span className="text-[10px]">Copy</span>
              </>
            )}
          </button>

          {onApplyCode && (
            <button
              type="button"
              onClick={handleApply}
              className="inline-flex items-center gap-1 rounded bg-primary/20 px-2 py-0.5 font-medium text-primary transition-colors hover:bg-primary/30"
              title="Review proposed changes in Monaco Diff Editor"
            >
              <ArrowRight className="h-3 w-3" />
              <span className="text-[10px]">{hasDiff ? 'Review in Editor' : 'Apply to Editor'}</span>
            </button>
          )}
        </div>
      </div>

      {/* Code Body */}
      {hasDiff && viewMode === 'diff' ? (
        <div className="overflow-x-auto py-1 font-mono text-[11px] leading-relaxed select-text">
          {autoDiffResult
            ? autoDiffResult.lines.map((item, lIdx) => {
                if (item.type === 'del') {
                  return (
                    <div
                      key={lIdx}
                      className="flex items-start bg-[#4a2128] border-l-2 border-[#ff7b72] px-2 py-0.5 text-[#ffb4ab]"
                    >
                      <span className="w-5 shrink-0 select-none text-right pr-2 text-[#ff7b72] font-bold">
                        -
                      </span>
                      <span className="whitespace-pre overflow-x-auto">
                        {item.text}
                      </span>
                    </div>
                  );
                }

                if (item.type === 'add') {
                  return (
                    <div
                      key={lIdx}
                      className="flex items-start bg-[#2b593a] border-l-2 border-[#46c466] px-2 py-0.5 text-[#e6ffed]"
                    >
                      <span className="w-5 shrink-0 select-none text-right pr-2 text-[#46c466] font-bold">
                        +
                      </span>
                      <span className="whitespace-pre overflow-x-auto font-medium">
                        {item.text}
                      </span>
                    </div>
                  );
                }

                return (
                  <div
                    key={lIdx}
                    className="flex items-start px-2 py-0.5 text-neutral-300 hover:bg-white/[0.03]"
                  >
                    <span className="w-5 shrink-0 select-none text-right pr-2 text-neutral-600 font-mono text-[10px]">
                      {lIdx + 1}
                    </span>
                    <span className="whitespace-pre overflow-x-auto">{item.text}</span>
                  </div>
                );
              })
            : rawLines.map((line, lIdx) => {
                const isAdd = line.startsWith('+') && !line.startsWith('+++');
                const isDel = line.startsWith('-') && !line.startsWith('---');
                const isHeader =
                  line.startsWith('@@') ||
                  line.startsWith('---') ||
                  line.startsWith('+++') ||
                  line.startsWith('diff --git');

                if (isDel) {
                  return (
                    <div
                      key={lIdx}
                      className="flex items-start bg-[#4a2128] border-l-2 border-[#ff7b72] px-2 py-0.5 text-[#ffb4ab]"
                    >
                      <span className="w-5 shrink-0 select-none text-right pr-2 text-[#ff7b72] font-bold">
                        -
                      </span>
                      <span className="whitespace-pre overflow-x-auto">
                        {line.slice(1)}
                      </span>
                    </div>
                  );
                }

                if (isAdd) {
                  return (
                    <div
                      key={lIdx}
                      className="flex items-start bg-[#2b593a] border-l-2 border-[#46c466] px-2 py-0.5 text-[#e6ffed]"
                    >
                      <span className="w-5 shrink-0 select-none text-right pr-2 text-[#46c466] font-bold">
                        +
                      </span>
                      <span className="whitespace-pre overflow-x-auto font-medium">
                        {line.slice(1)}
                      </span>
                    </div>
                  );
                }

                if (isHeader) {
                  return (
                    <div
                      key={lIdx}
                      className="px-2 py-0.5 text-neutral-400 font-mono text-[10px] bg-white/[0.04] border-y border-white/[0.06]"
                    >
                      {line}
                    </div>
                  );
                }

                return (
                  <div
                    key={lIdx}
                    className="flex items-start px-2 py-0.5 text-neutral-300 hover:bg-white/[0.03]"
                  >
                    <span className="w-5 shrink-0 select-none text-right pr-2 text-neutral-600 font-mono text-[10px]">
                      {lIdx + 1}
                    </span>
                    <span className="whitespace-pre overflow-x-auto">{line}</span>
                  </div>
                );
              })}
        </div>
      ) : (
        <pre className="overflow-x-auto p-3 font-mono text-[11px] leading-relaxed text-emerald-300">
          <code>{hasDiff && viewMode === 'clean' ? cleanCode : code}</code>
        </pre>
      )}
    </div>
  );
}

/**
 * Lightweight, safe Markdown & Code block renderer for AI responses.
 * Highlights code fences with syntax styling, copy-to-clipboard, and Apply to Editor.
 */
function MarkdownBlock({
  content,
  activeFileContent,
  activeSelectionText,
  onApplyCode,
}: {
  content: string;
  activeFileContent?: string | null;
  activeSelectionText?: string | null;
  onApplyCode?: (code: string) => void;
}) {
  const parts = useMemo(() => {
    const segments: Array<
      | { type: 'text'; value: string }
      | { type: 'code'; language: string; code: string }
    > = [];

    const regex = /```([a-zA-Z0-9_-]+)?\r?\n([\s\S]*?)```/g;
    let lastIndex = 0;
    let match: RegExpExecArray | null;

    while ((match = regex.exec(content)) !== null) {
      if (match.index > lastIndex) {
        segments.push({
          type: 'text',
          value: content.slice(lastIndex, match.index),
        });
      }

      segments.push({
        type: 'code',
        language: match[1]?.trim() || 'code',
        code: match[2]?.trimEnd() || '',
      });

      lastIndex = regex.lastIndex;
    }

    if (lastIndex < content.length) {
      segments.push({
        type: 'text',
        value: content.slice(lastIndex),
      });
    }

    return segments;
  }, [content]);

  return (
    <div className="space-y-2.5 text-xs leading-relaxed text-foreground/90">
      {parts.map((part, idx) => {
        if (part.type === 'code') {
          return (
            <CodeBlockCard
              key={idx}
              language={part.language}
              code={part.code}
              activeFileContent={activeFileContent}
              activeSelectionText={activeSelectionText}
              onApplyCode={onApplyCode}
            />
          );
        }

        // Render formatted text paragraphs with basic inline code and bolding
        return (
          <div key={idx} className="space-y-1.5 whitespace-pre-wrap">
            {part.value}
          </div>
        );
      })}
    </div>
  );
}

